def balance_repair_records(records):
    """提高工具与上下文样本的采样频次，新增条目是重复采样而非新素材。"""
    output = list(records)
    for row in records:
        if row.get('provenance', {}).get('scenario') not in {'tool', 'error', 'cancel', 'memory'}:
            continue
        for repeat in (1, 2):
            item = copy.deepcopy(row)
            item['id'] += f'-repeat-{repeat}'
            item['provenance']['sampling_repeat'] = repeat
            output.append(item)
    return output
