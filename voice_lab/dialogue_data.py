FILLERS = re.compile(r'^[嗯啊哦呃额唉噢哎诶呀唔哈]+$')


def normalize_audio_text(text):
    """核对转写时统一常见中文数字与阿拉伯数字，保留原始文本。"""
    digits = dict(zip('零〇一二两三四五六七八九', [0, 0, 1, 2, 2, 3, 4, 5, 6, 7, 8, 9]))
    multipliers = {'十': 10, '百': 100, '千': 1000}

    def number(match):
        value = match.group()
        if not any(char in '十百千万' for char in value):
            return ''.join(str(digits[char]) for char in value)
        total, section, current = 0, 0, 0
        for char in value:
            if char in digits:
                current = digits[char]
            elif char == '万':
                total += (section + current) * 10000
                section, current = 0, 0
            else:
                section += (current or 1) * multipliers[char]
                current = 0
        return str(total + section + current)

    text = re.sub(r'[零〇一二两三四五六七八九十百千万]+', number, text)
    return re.sub(r'\W', '', text).lower()


def spoken_numbers(text):
    # 固定表达和选择代词里的“一”不代表需要逐字核对的事实数值。
    text = re.sub(r'哪一(?=[种个位张条家本页天年次段])', '哪', text)
    text = re.sub(r'一(?=下|起|些|会儿?|直|样|共|切)', '', text)
    text = re.sub(r'一(?=点(?![零〇一二两三四五六七八九0-9]))', '', text)
    text = re.sub(r'([想看查说听试数算读问练])一\1', r'\1\1', text)
    groups = re.findall(r'[〇零一二两三四五六七八九十百千万0-9]+', text)
    return [normalize_audio_text(group) for group in groups]


def clean_filler_turns(units):
    """按完整说话轮次清理，保留一秒分块中属于完整句子的短词。"""
    cleaned = copy.deepcopy(units)
    beginning = None
    changed = 0
    for index, unit in enumerate(units):
        if unit.get('listen'):
            continue
        if beginning is None:
            beginning = index
        if not unit.get('end'):
            continue
        turn = units[beginning:index + 1]
        text = ''.join(item.get('text', '') for item in turn)
        normalized = re.sub(r'\W', '', text)
        controls = any(item.get('delegate') or item.get('cancel') or 'backend' in item for item in turn)
        if normalized and FILLERS.fullmatch(normalized) and not controls:
            for position in range(beginning, index + 1):
                cleaned[position] = {'listen': True}
            changed += 1
        beginning = None
    return cleaned, changed


def spoken_units(text, tokenizer, max_tokens, characters=6):
    """用接近口语语速的短块监督流式输出，避免一秒填入整段长答。"""
    from .prepare import target_ids
    parts = []
    pending = ''
    for character in text:
        candidate = pending + character
        if pending and (len(candidate) > characters or len(target_ids({'text': candidate, 'end': True}, tokenizer)) > max_tokens):
            parts.append(pending)
            pending = character
        else:
            pending = candidate
    if pending:
        parts.append(pending)
    return [{'text': part, 'end': index == len(parts) - 1} for index, part in enumerate(parts)]


